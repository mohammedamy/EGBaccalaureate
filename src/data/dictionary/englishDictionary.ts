/**
 * Helper to look up a word in the dictionary
 */
export const lookupEnglishWord = (query: string): DictionaryEntry | undefined => {
  const normalized = query.trim().toLowerCase();
  return ENGLISH_DICTIONARY.find(
    (entry) =>
      entry.word.toLowerCase() === normalized ||
      entry.id.toLowerCase() === normalized
  );
};

/**
 * Search the dictionary with fuzzy matching
 */
export const searchEnglishDictionary = (
  query: string,
  categoryFilter: string = 'all',
  posFilter: string = 'all'
): DictionaryEntry[] => {
  const q = query.trim().toLowerCase();
  return ENGLISH_DICTIONARY.filter((entry) => {
    const matchesCategory =
      categoryFilter === 'all' || entry.category === categoryFilter;
    const matchesPos = posFilter === 'all' || entry.partOfSpeech === posFilter;

    if (!matchesCategory || !matchesPos) return false;
    if (!q) return true;

    return (
      entry.word.toLowerCase().includes(q) ||
      entry.definition.toLowerCase().includes(q) ||
      entry.arabicTranslation.includes(q) ||
      entry.collocations.some((c) => c.toLowerCase().includes(q)) ||
      entry.synonyms.some((s) => s.toLowerCase().includes(q)) ||
      entry.antonyms.some((a) => a.toLowerCase().includes(q))
    );
  });
};

export function getOfficialBookById(id: string): OfficialBook | undefined {
  return officialBooksList.find((b) => b.id === id);
}

export function getOfficialBookByBranch(branchId: string): OfficialBook | undefined {
  return officialBooksList.find((b) => {
    if (b.branchId === branchId) return true;
    if (branchId === 'algebra_solid' && (b.branchId === 'algebra_solid' || b.branchId === 'pure-math-algebra-solid')) return true;
    if (branchId === 'calculus' && (b.branchId === 'calculus' || b.branchId === 'pure-math-calculus')) return true;
    if (branchId === 'statics' && (b.branchId === 'statics' || b.branchId === 'applied-math-statics')) return true;
    if (branchId === 'dynamics' && (b.branchId === 'dynamics' || b.branchId === 'applied-math-dynamics')) return true;
    if (branchId === 'egbac_vectors_geometry' && (b.branchId === 'egbac_vectors_geometry' || b.branchId === 'egbac-vectors-geometry' || b.branchId === 'egbac-discrete')) return true;
    if (branchId === 'egbac_analysis' && (b.branchId === 'egbac_analysis' || b.branchId === 'egbac-analysis')) return true;
    if (branchId === 'egbac_mechanics' && (b.branchId === 'egbac_mechanics' || b.branchId === 'egbac-mechanics')) return true;
    if (branchId === 'egbac_probability' && (b.branchId === 'egbac_probability' || b.branchId === 'egbac-probability')) return true;
    return false;
  });
}

export function getOfficialBooksByCurriculum(curriculum: 'thanaweya' | 'egbac' | 'all'): OfficialBook[] {
  if (curriculum === 'all') return officialBooksList;
  return officialBooksList.filter((b) => b.curriculum === curriculum || b.curriculum === 'both');
}

export function getOfficialBooksBySubject(subjectId: 'all' | 'mathematics' | 'physics' | 'chemistry' | 'biology'): OfficialBook[] {
  if (subjectId === 'all') return officialBooksList;
  return officialBooksList.filter((b) => b.subjectId === subjectId);
}
